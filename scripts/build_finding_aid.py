#!/usr/bin/env python3
"""build_finding_aid.py: the angelology finding aid (replaces the quarantined docs/ANGELICRESEARCH.md).

    python scripts/build_finding_aid.py [--out docs/ANGELICRESEARCH.md]

Built ONLY from data: verified claims, packet meta (coverage and limits), scores, links and their disputes, open questions,
semantic verdicts. It contains structural labels and the claims' own restatements; it asserts nothing of its own about Pico or
the scholars. Purpose (P20260926003059): help an orchestrator or coding agent find the angelic material in the Oration,
Commento, Heptaplus and De ente et uno, and what Allen, Black and the other scholars in the corpus say about it.
"""
import argparse, glob, io, json, os, sys
from collections import Counter, defaultdict
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import claims_verify as V


def load(p):
    with io.open(p, encoding="utf-8") as fh:
        return json.load(fh)


def cut(s, n=170):
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "ANGELICRESEARCH.md"))
    ap.add_argument("--domain", default="angelology")
    a = ap.parse_args()
    ddir = os.path.join(ROOT, "data", "claims", a.domain)
    topics = {t["id"]: t for t in load(os.path.join(ROOT, "data", "claims", "topics.json"))["topics"]}
    sc = load(os.path.join(ddir, "scores.json"))
    scores = sc["claims"]
    oq = load(os.path.join(ddir, "open_questions.json"))["open_questions"]
    reg = load(os.path.join(ROOT, "data", "corpus", "registry.json"))["works"]
    claims, packets, sem = {}, {}, {}
    for f in sorted(glob.glob(os.path.join(ddir, "*.claims.json"))):
        p = load(f)
        pk = p["packet"]
        vf = os.path.join(ROOT, "data", "verification", "claims", pk + ".verdicts.json")
        st = {c["id"]: c["status"] for c in load(vf)["claims"]} if os.path.exists(vf) else {}
        meta_p = os.path.join(ROOT, "data", "claims", "_work", pk + ".meta.json")
        meta = load(meta_p) if os.path.exists(meta_p) else {}
        s = V.semantic_verdicts(pk)
        packets[pk] = {"meta": meta, "n": 0, "judged": 0, "supported": 0, "work": (meta.get("scope") or {}).get("work")}
        for c in p["claims"]:
            if st.get(c["id"]) != "verified":
                continue
            c["_pk"] = pk
            claims[c["id"]] = c
            packets[pk]["n"] += 1
            j = s.get(c["id"])
            if j and j.get("hash") == V.chash(c):
                packets[pk]["judged"] += 1
                if j["verdict"] == "supported":
                    packets[pk]["supported"] += 1
                c["_sem"] = j["verdict"]
    links, disputes = [], []
    for f in sorted(glob.glob(os.path.join(ddir, "*.links.json"))):
        d = load(f)
        links += d.get("links", [])
        disputes += [dict(x, _src=os.path.basename(f)) for x in d.get("disputes", [])]
    n_sup = sum(1 for c in claims.values() if c.get("_sem") == "supported")
    out = []
    w = out.append
    w("# Angelology and the One: finding aid")
    w("")
    w("*Generated by `scripts/build_finding_aid.py` on %s from verified claims. Do not edit: regenerate. It replaces the earlier "
      "`ANGELICRESEARCH.md`, which the audit (`audit/A3_angelology_neoplatonism.md`) found to contain invented material; that file is archived in "
      "`docs/archive/v1-angelology/`.*" % datetime.now(timezone.utc).strftime("%Y-%m-%d"))
    w("")
    w("**State.** %d claims passed the quotation gate (every quotation re-found in its source by `scripts/claims_verify.py`); "
      "%d of them have been judged `supported` by a second reader at their current wording; %d links between claims; %d recorded disputes; %d open questions. "
      "A claim that is not `supported` may not be cited in prose (`scripts/commentary_check.py`)." % (len(claims), n_sup, len(links), len(disputes), len(oq)))
    w("")
    w("## 1. How to find and use the material")
    w("")
    w("```")
    w("python scripts/claims_query.py --topics                      topics with claim counts")
    w("python scripts/claims_query.py --topic three-worlds --full   the claims on a topic, with quotations and warrants")
    w("python scripts/claims_query.py --locus oration --full        claims about a place in Pico's text")
    w("python scripts/claims_query.py --claimant Black --text Anaxagoras")
    w("python scripts/claims_query.py --party ficino --min-importance 20")
    w("python scripts/corpus_tool.py show black2006 8400 8520       read the source around a cited line")
    w("open site/cards/index.html  (python scripts/build_cards.py)  browse the same claims as cards")
    w("```")
    w("")
    w("Cite as `[[claim-id]]` in prose; every claim id is `<packet>:<nnn>`; every quotation carries `work:line` (`data/corpus/registry.json` maps the work key to its file).")
    w("")
    w("## 2. Coverage: what has been read, and what has not")
    w("")
    w("| packet | work | claims | judged | supported | not mined (first items, from the researcher's own record) |")
    w("|---|---|---|---|---|---|")
    for pk, d in sorted(packets.items()):
        nm = d["meta"].get("not_mined") or []
        wk = d["work"] or ""
        w("| %s | %s | %d | %d | %d | %s |" % (pk, (reg.get(wk, {}).get("title") or wk)[:48], d["n"], d["judged"], d["supported"], "; ".join(cut(x, 70) for x in nm[:2]).replace("|", "/")))
    w("")
    w("Full lists: `data/claims/_work/<packet>.meta.json` (`not_mined`, `notes`: book maps with chapter line ranges, cruxes, OCR trouble).")
    w("")
    w("**Not in the corpus** (per audit A3 s8; check `python scripts/corpus_tool.py works` before relying on this): Pico's *Commento* itself (Garin's edition, Jayne's translation): "
      "it is reached only through Allen's essay, so every Commento claim is a claim *about* it; Aquinas's *Summa*, the *Enneads* and the Dionysian corpus: "
      "those strands rest on scholars' claims. Ficino's and Pico's letters are in the corpus only as quoted by scholars.")
    w("")
    w("## 3. Where the angelic material is in Pico's texts")
    w("")
    by_text = defaultdict(list)
    for loc, d in sc["loci"].items():
        text = loc.split(" | ")[0]
        by_text[text].append((loc.split(" | ", 1)[1] if " | " in loc else "", d))
    for text in sorted(by_text, key=lambda t: -sum(x[1]["claims"] for x in by_text[t])):
        rows = sorted(by_text[text], key=lambda r: -r[1]["claims"])
        w("### %s (%d places)" % (text, len(rows)))
        w("")
        w("| place | claims | importance | most important claims |")
        w("|---|---|---|---|")
        for ref, d in rows[:30]:
            w("| %s | %d | %.0f | %s |" % (ref.replace("|", "/")[:70], d["claims"], d["importance"], ", ".join("`%s`" % x for x in d["top_claims"][:3])))
        w("")
    w("## 4. By topic")
    w("")
    for t, d in sorted(sc["topics"].items(), key=lambda kv: -kv[1]["claims"]):
        lab = topics.get(t, {}).get("label", t)
        w("### `%s`: %s" % (t, cut(lab, 140)))
        w("")
        w("%d claims; %d primary-tier; claimants: %s." % (d["claims"], d["primary_claims"], ", ".join(d["claimants"][:8]) + (" ..." if len(d["claimants"]) > 8 else "")))
        w("")
        for cid in d["top_claims"][:5]:
            c = claims.get(cid)
            if c:
                w("- `%s` (%s, %s, importance %.0f): %s" % (cid, c["claimant"], c["hedge"], scores[cid]["importance"], cut(c["text"])))
        w("")
    w("## 5. Recorded disagreements between scholars")
    w("")
    if not disputes:
        w("None recorded yet (linking incomplete: `TICKETS.md` T-CLAIMS-04).")
    for x in disputes:
        ids = x.get("claims") or []
        w("- **%s**: %s (%s)" % (x.get("topic", ""), x.get("about", ""), ", ".join("`%s`" % i for i in ids)))
    w("")
    w("## 6. Open questions the sources leave open (ranked by the importance of the claim they arise from)")
    w("")
    for o in oq[:40]:
        w("- `%s` [%s, %s]: %s" % (o["claim"], o["kind"].replace("_", " "), o["claimant"], cut(o["text"], 230)))
    w("")
    w("## 7. Related")
    w("")
    w("`docs/CLAIMS_MODEL.md` (what a claim is and how it is verified and scored); `docs/briefs/` (how to run researchers, verifiers, linkers, writers); "
      "`data/claims/` (packets, links, scores); `docs/angelology/` (commentary written from these claims); `audit/A3_angelology_neoplatonism.md` (why the earlier version was withdrawn).")
    with io.open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote %s (%d lines; %d claims, %d supported)" % (os.path.relpath(a.out, ROOT), len(out), len(claims), n_sup))


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main())
